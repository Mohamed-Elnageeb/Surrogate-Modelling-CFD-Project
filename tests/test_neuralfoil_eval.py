"""Validation of the low-fidelity evaluator against textbook NACA0012 data.

These tests are the credibility gate for any result produced with the
low-fidelity oracle: if they fail, numbers generated by the design loop should
not be trusted or reported.
"""

import pytest

np = pytest.importorskip("numpy")
pytest.importorskip("neuralfoil")

from cfdagent.lowfid.neuralfoil_eval import evaluate_design, run_lowfid

BASELINE = np.zeros(10)  # zero design vector == NACA0012


def test_baseline_matches_published_naca0012_polar():
    out = evaluate_design(BASELINE, alpha=4.0, reynolds=1e6)
    # Published NACA0012 at alpha=4 deg, Re=1e6: Cl ~ 0.43-0.46, Cd ~ 0.0075-0.009
    assert out["Cl"] == pytest.approx(0.43, abs=0.05)
    assert 0.006 < out["Cd"] < 0.010
    assert out["Cl"] / out["Cd"] > 40


def test_symmetric_section_has_zero_lift_at_zero_incidence():
    out = evaluate_design(BASELINE, alpha=0.0, reynolds=1e6)
    assert out["Cl"] == pytest.approx(0.0, abs=0.02)


def test_lift_slope_matches_thin_airfoil_theory():
    alphas = [0.0, 2.0, 4.0, 6.0]
    cls = [evaluate_design(BASELINE, alpha=a, reynolds=1e6)["Cl"] for a in alphas]
    slope = np.polyfit(alphas, cls, 1)[0]
    # Thin-airfoil theory gives 2*pi per radian = 0.1097 per degree.
    assert slope == pytest.approx(0.1097, rel=0.10)


def test_drag_increases_with_incidence():
    cds = [evaluate_design(BASELINE, alpha=a, reynolds=1e6)["Cd"] for a in (0.0, 4.0, 8.0)]
    assert cds[0] < cds[1] < cds[2]


def test_run_lowfid_returns_run_cfd_compatible_dict():
    result = run_lowfid("abc", BASELINE)
    for key in ("design_id", "design_vec", "Cl", "Cd", "success", "invalid_metrics"):
        assert key in result
    assert result["success"] is True
    assert result["error"] is None
    assert result["fidelity"] == "neuralfoil"


def test_run_lowfid_flags_low_confidence():
    # An impossible confidence floor forces the validation path to trigger.
    result = run_lowfid("abc", BASELINE, min_confidence=2.0)
    assert result["success"] is False
    assert result["invalid_metrics"] is True
    assert "confidence" in result["error"]
    assert result["Cl"] is None
