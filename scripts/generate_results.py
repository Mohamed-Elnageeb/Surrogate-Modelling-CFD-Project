        f"| Drag vs {trans['drag_free'].dataset} (**free transition**) | "
        f"{trans['drag_free'].n} | **{trans['drag_free'].mean_abs_pct:.1f}%** | "
        f"{trans['drag_free'].bias_pct:+.1f}% |",
        f"| Lift vs {trans['lift_tripped'].dataset.replace(' (lift)', '')} | "
        f"{trans['lift_tripped'].n} | {trans['lift_tripped'].mean_abs_pct:.1f}% | "
        f"{trans['lift_tripped'].bias_pct:+.1f}% |",
