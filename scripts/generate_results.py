#!/usr/bin/env python3
"""Regenerate RESULTS.md from live runs, so the documented numbers cannot drift.

Every value in RESULTS.md is produced here rather than typed by hand. Run after
any change that could move a result:

    python scripts/generate_results.py
"""

from __future__ import annotations

import datetime as dt
import platform
import subprocess
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from cfdagent.cfd.bl_mesher import BLMeshConfig, first_cell_height  # noqa: E402
from cfdagent.experiments.convention_census import run as census_run  # noqa: E402
from cfdagent.experiments.convention_error import run as convention_run  # noqa: E402
from cfdagent.lowfid.neuralfoil_eval import evaluate_design  # noqa: E402
from cfdagent.validation.transition_study import run as transition_run  # noqa: E402

REPO = Path(__file__).resolve().parents[1]


def _versions() -> str:
    import importlib.metadata as md

    names = ["numpy", "scipy", "torch", "neuralfoil", "aerosandbox", "gmsh"]
    parts = []
    for n in names:
        try:
            parts.append(f"{n} {md.version(n)}")
        except Exception:
            pass
    return ", ".join(parts)


def _git_sha() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"], cwd=REPO, text=True
        ).strip()
    except Exception:
        return "unknown"


def main() -> None:
    conv = convention_run()
    census = census_run()
    trans = transition_run()

    # Low-fidelity evaluator validation points
    base = np.zeros(10)
    a4 = evaluate_design(base, alpha=4.0, reynolds=1e6)
    a0 = evaluate_design(base, alpha=0.0, reynolds=1e6)
    alphas = [0.0, 2.0, 4.0, 6.0]
    slope = np.polyfit(
        alphas, [evaluate_design(base, alpha=a, reynolds=1e6)["Cl"] for a in alphas], 1
    )[0]

    cfg1, cfg6 = BLMeshConfig(reynolds=1e6), BLMeshConfig(reynolds=6e6)

