        f"| Cl at alpha=4 deg, Re=1e6 | {a4['Cl']:.4f} | 0.43 - 0.46 |",
        f"| Cd at alpha=4 deg, Re=1e6 | {a4['Cd']:.5f} | 0.0075 - 0.009 |",
        f"| L/D at alpha=4 deg | {a4['Cl'] / a4['Cd']:.1f} | 50 - 60 |",
        "",
        f"Lift-curve slope is {100 * slope / 0.1097:.0f}% of thin-airfoil theory.",
        "",
        "## 2. Coordinate ordering costs a factor of nine in drag",
        "",
        "| Ordering | Cl | Cd | L/D |",
        "|---|---|---|---|",
        f"| LE-anchored (as emitted) | {conv['le_anchored']['Cl']:.4f} | "
        f"{conv['le_anchored']['Cd']:.5f} | {conv['le_anchored']['LD']:.1f} |",
        f"| Selig (corrected) | {conv['selig']['Cl']:.4f} | "
        f"{conv['selig']['Cd']:.5f} | {conv['selig']['LD']:.1f} |",
        f"| Reference NACA0012 | {conv['reference']['Cl']:.4f} | "
        f"{conv['reference']['Cd']:.5f} | {conv['reference']['LD']:.1f} |",
        "",
        f"Drag overprediction from ordering alone: **{conv['drag_error_factor']:.1f}x**. "
        f"Maximum geometric deviation from a true NACA0012: "
        f"**{conv['max_geometry_deviation']:.2e}** - the shape is exact, only the "
        "ordering differs, and no validity check in the pipeline rejects it.",
        "",
        "## 3. Is the ordering hazard widespread? No (negative result)",
        "",
        f"Of **{census['total']}** airfoils in the UIUC database as redistributed with "
        f"AeroSandbox: **{census['selig']} Selig**, **{census['lednicer']} Lednicer**, "
        f"**{census['other']} other**.",
        "",
        "The curated corpus is uniformly trailing-edge-anchored, so this was a defect",
        "in our own generator rather than contamination of the data the field trains on.",
        "",
        "## 4. Boundary-layer mesh sizing",
        "",
        "| Reynolds number | First cell for y+ ~ 1 | BL thickness | Farfield |",
        "|---|---|---|---|",
        f"| 1e6 | {cfg1.first_layer():.3e} c | {cfg1.bl_thickness():.3e} c | "
        f"{cfg1.farfield_radius:.0f} c |",
        f"| 6e6 | {cfg6.first_layer():.3e} c | {cfg6.bl_thickness():.3e} c | "
        f"{cfg6.farfield_radius:.0f} c |",
        "",
        "The original mesh had 9.55e-03 c wall spacing and a 20.5 c farfield, i.e. "
        f"**{9.55e-3 / first_cell_height(1e6):.0f}x** too coarse at Re=1e6 to resolve "
        "viscous drag.",
        "",
        "### Effect on a NACA0012 (SU2, Re=1e6, alpha=4 deg)",
        "",
        "| | Original mesh | BL-resolved mesh | Published |",
        "|---|---|---|---|",
        "| Cl | 0.0709 | **0.4419** | 0.43 - 0.46 |",
        "| Cd | 0.0236 | 0.01108 | - |",
        "| L/D | 3.0 | **39.9** | - |",
        "| Final rms[Rho] | -3.48 (target -12) | -4.67, still falling | - |",
        "",
        "The original case exhausted all 2200 iterations without converging. An "
